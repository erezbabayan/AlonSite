#!/usr/bin/env node
// Scans images/<category>/ (skipping images/thumbs/) and writes gallery-data.js,
// a plain <script> file (no fetch/CORS issues when opened via file://) exposing
// window.GALLERY_DATA = { categories: [{ key, label, images: [{ full, thumb, alt }] }] }.
// Re-run after generate-thumbs.js whenever photos are added or removed.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const IMAGES_DIR = path.join(ROOT, "images");
const EXT_RE = /\.(jpe?g|png)$/i;

// Narrative order (life-story flow) rather than alphabetical.
const CATEGORY_ORDER = [
  "ילדות ובגרות",
  "בר מצווה אלון",
  "חברים",
  "צבא",
  "משפחה",
  "כתבים של אלון",
  "הלוויה",
  "הנצחה",
  "אתר הנצחה",
  "עיתונות",
  "כללי",
];

function isCategoryDir(name) {
  return name !== "thumbs" && !name.startsWith(".");
}

const allDirs = fs
  .readdirSync(IMAGES_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && isCategoryDir(d.name))
  .map((d) => d.name);

const orderedDirs = [
  ...CATEGORY_ORDER.filter((c) => allDirs.includes(c)),
  ...allDirs.filter((c) => !CATEGORY_ORDER.includes(c)),
];

function slugify(name) {
  return name.replace(/\s+/g, "-");
}

function toUrl(...parts) {
  return parts.map((p) => encodeURIComponent(p)).join("/");
}

const categories = orderedDirs.map((category) => {
  const srcDir = path.join(IMAGES_DIR, category);
  const files = fs
    .readdirSync(srcDir, { withFileTypes: true })
    .filter((f) => f.isFile() && EXT_RE.test(f.name))
    .map((f) => f.name)
    .sort((a, b) => a.localeCompare(b, "he"));

  const images = files.map((name) => {
    const thumbName = name.replace(EXT_RE, ".jpg");
    return {
      full: `images/${toUrl(category)}/${toUrl(name)}`,
      thumb: `images/thumbs/${toUrl(category)}/${toUrl(thumbName)}`,
      alt: `${category} - ${name.replace(EXT_RE, "")}`,
    };
  });

  return { key: slugify(category), label: category, images };
});

const totalImages = categories.reduce((sum, c) => sum + c.images.length, 0);

const output = `// AUTO-GENERATED by scripts/generate-gallery-data.js — do not edit by hand.
// Regenerate with: node scripts/generate-thumbs.js && node scripts/generate-gallery-data.js
window.GALLERY_DATA = ${JSON.stringify({ categories }, null, 2)};
`;

fs.writeFileSync(path.join(ROOT, "gallery-data.js"), output, "utf8");
console.log(`Wrote gallery-data.js — ${categories.length} categories, ${totalImages} images.`);
